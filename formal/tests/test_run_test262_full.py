        exporter._spawn = mock.MagicMock()

        result = exporter.export(12, 34, 10)

        self.assertEqual(result.returncode, 0)
        exporter.process.stdin.write.assert_called_once_with("EXPORT 12 34\n")
        exporter.process.stdin.flush.assert_called_once_with()
        exporter._spawn.assert_not_called()
        exporter._terminate.assert_not_called()

