    def test_dry_run_bootstraps_inventory_before_loading_it(self):
        events = []
        target = runner.Target(0, 7, "a.js")

        def bootstrap(_args):
            events.append("bootstrap")
            return "source"

        def load(_path, _prefix):
            self.assertEqual(events, ["bootstrap"])
            events.append("load")
            return [target]

        with tempfile.TemporaryDirectory() as directory:
            with (
                mock.patch.object(runner, "bootstrap_inventory", bootstrap),
                mock.patch.object(runner, "load_inventory", load),
                mock.patch.object(
                    runner, "source_fingerprint", return_value="source"
                ),
                mock.patch.object(runner, "RunLock", mock.MagicMock()),
                mock.patch.object(runner, "ensure_campaign") as ensure,
                mock.patch.object(runner, "read_results", return_value={}),
            ):
                result = runner.main(
                    [
                        "--dry-run",
                        "--state-dir",
                        str(Path(directory) / "state"),
                    ]
                )

        self.assertEqual(result, 0)
        self.assertEqual(events, ["bootstrap", "load"])
        self.assertFalse(ensure.call_args.kwargs["create"])

